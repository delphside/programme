#!/usr/bin/env python3
"""design-map.py — draws an application's design map, `docs/R.2.0-design-map.md`,
and a project's change to it.

The source is the application's `docs/design-map/`: `model.dsl` (the C4
model), `views.dsl` (its views) and `map.dsl` (the model with the views), in
Structurizr's DSL. The views are exported to Mermaid, never drawn by hand.
R is the application's document range, from its programme profile.

**Four commands, and only the writing ones need Docker.**

  design-map.py --write   export map.dsl through the Structurizr image, pinned
                          by digest in IMAGE, and write the document
  design-map.py --check   exit 1 if the sources' hash differs from the one in
                          the document's header; plain Python, no Docker
  design-map.py --change N-map-change.md --write
                          draw a project's change file, one section per work
                          package, into N-map-diagrams.md beside it
  design-map.py --change N-map-change.md --check
                          exit 1 if the change file or the map changed since
                          N-map-diagrams.md was drawn; no Docker

The hash covers every file in `docs/design-map/` (and, for a change file, the
change file too), so `--check` says "regenerate" for any change to the
sources, and `check-docs.sh` can run it in hooks and cloud sessions where
Docker is not available. A hand edit to the generated document is not caught
by the hash; the header says not to make one.

Each view becomes a section titled by its C4 type and its description in
views.dsl, in the order views.dsl lists them. `lifecycles.md`, when it exists,
is appended as it stands.

**The change file** is Markdown with a `structurizr` fenced block holding an
extension of the map. Every statement in its `model { }` is an entry and names
the one work package it belongs to by a `wp:N` tag; `!element X { }` with no
tags of its own is a wrapper for entries. The command filters the entries per
package, builds a view of each package's elements (a Component view of their
container, or a Container view where they span containers), and exports it.
A heading in the file that names `#N` titles that package's section.

**Relationship states.** In every export, a relationship tagged `new`,
`changed` or `removed` is drawn in the colours of the change key
(`docs/diagrams/README.md` in Tile Lite Elite) and its label starts with the
state, so the state reads without colour.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from board import profile  # noqa: E402

IMAGE = ("structurizr/structurizr@sha256:"
         "721136283c2f9cf1ba69037bc9de136c579d66fdcb2d771cb60546ec68def1a5")

VIEW = re.compile(r'^\s*(container|component)\s+\S+\s+"([^"]+)"\s+"([^"]+)"', re.M)
HASH = re.compile(r"^Sources hash: `([0-9a-f]{64})`\.$", re.M)

# The change key's strokes, from `docs/diagrams/README.md` in Tile Lite Elite.
STATE_COLOURS = {"new": "#1a7f37", "changed": "#9a6700", "removed": "#cf222e"}

# A Mermaid edge as Structurizr writes it: `SRC-. "<div>label</div>..." .->DST`.
EDGE = re.compile(r'^(\s*)(\S+?)-\. "(.*)" \.->(\S+)\s*$')
LINK = re.compile(r"-\.|-->|---|==|--|~~~")
FIRST_DIV = re.compile(r"<div>(.*?)</div>")
QUOTED = re.compile(r'"([^"]*)"')
PACKAGE_TAG = re.compile(r"^wp:(\d+)$")
HEADING = re.compile(r"^#{1,6}\s+(.*\S)\s*$")


def paths() -> tuple[Path, Path, Path]:
    root = profile.app_root()
    rng = profile.application_profile(root)["identity"]["document_range"]
    return root, root / "docs" / "design-map", root / "docs" / f"{rng}.2.0-design-map.md"


def sources_hash(source: Path) -> str:
    """One hash over every file's name and bytes, in name order."""
    h = hashlib.sha256()
    for f in sorted(p for p in source.rglob("*") if p.is_file()):
        h.update(f.relative_to(source).as_posix().encode() + b"\0")
        h.update(f.read_bytes() + b"\0")
    return h.hexdigest()


def header(title: str, digest: str) -> str:
    return f"""# {title}

**Generated by the programme's `scripts/docs/design-map/design-map.py` from
[`design-map/`](design-map/). Do not edit.**

The application as it is on `main`, drawn from one model. To change a
diagram, change [`model.dsl`](design-map/model.dsl) and run the script with
`--write`. Each element's `artefact` property in `model.dsl` names the file or
crate that implements it.

Sources hash: `{digest}`.
"""


def export(source: Path, out: Path, workspace: str = "map.dsl") -> None:
    """Export `workspace` to Mermaid and to JSON. The image takes one `-f` per
    run and has no shell to chain two, so it is run once for each."""
    for fmt in ("mermaid", "json"):
        subprocess.run(
            ["docker", "run", "--rm", "-u", f"{os.getuid()}:{os.getgid()}",
             "-v", f"{source}:/w:ro", "-v", f"{out}:/out", "-w", "/w", IMAGE,
             "export", "-w", workspace, "-f", fmt, "-o", "/out"],
            check=True, stdout=subprocess.DEVNULL)


class ExportError(Exception):
    """The Structurizr export is not in a form the post-processing knows."""


def _label(text: str) -> str:
    """A relationship's description as the Mermaid label shows it: the label
    wraps with `<br />`, where the description has a space."""
    return " ".join(text.replace("<br />", " ").split())


def _walk(node, found: list, parents: dict, parent=None) -> None:
    """Collect the workspace JSON's relationships, in file order, and each
    element's parent. An element has an `id` and sits in a people, systems,
    containers or components list; a relationship also has `sourceId`."""
    if isinstance(node, dict):
        if {"sourceId", "destinationId", "id"} <= node.keys():
            found.append(node)
        elif "id" in node:
            parents[node["id"]] = parent
            parent = node["id"]
        for value in node.values():
            _walk(value, found, parents, parent)
    elif isinstance(node, list):
        for value in node:
            _walk(value, found, parents, parent)


def _state(tags: str) -> str | None:
    return next((s for s in STATE_COLOURS if s in tags.split(",")), None)


def _drawn_state(rel: dict, explicit: list[dict], parents: dict) -> str | None:
    """The state to draw for a relationship. An explicit one draws its own. An
    implied one (a line between containers, derived from relationships between
    their components) draws that of the explicit relationships whose source is
    within its source and whose destination is within its destination: their
    state if all share one (an untagged one counts as unchanged), nothing if
    none is tagged, and `changed` otherwise."""
    if "linkedRelationshipId" not in rel:
        return _state(rel.get("tags", ""))

    def within(element: str, outer: str) -> bool:
        while element is not None:
            if element == outer:
                return True
            element = parents.get(element)
        return False

    states = {_state(r.get("tags", "")) for r in explicit
              if within(r["sourceId"], rel["sourceId"])
              and within(r["destinationId"], rel["destinationId"])}
    if states <= {None}:
        return None
    return states.pop() if len(states) == 1 else "changed"


def style_relationships(mermaid: str, workspace: dict) -> str:
    """Colour the lines of relationships tagged `new`, `changed` or `removed`,
    and start their labels with the state. Mermaid has no class for an edge, so
    each gets a `linkStyle` by its index among the edges, appended at the end.
    An edge is matched to its relationship by source, destination and
    description, which the Mermaid ids and labels carry (Structurizr refuses a
    second relationship with the same three). A line in a form other than
    `SRC-. "label" .->DST` raises ExportError, since an uncounted line would
    shift every index after it."""
    found: list[dict] = []
    parents: dict = {}
    _walk(workspace.get("model", {}), found, parents)
    known = {(r["sourceId"], r["destinationId"], _label(r.get("description", ""))): r
             for r in found}
    explicit = [r for r in found if "linkedRelationshipId" not in r]
    lines, styles, index = [], [], 0
    for line in mermaid.splitlines():
        edge = EDGE.match(line)
        if edge:
            indent, src, label, dst = edge.groups()
            first = FIRST_DIV.match(label)
            rel = known.get((src, dst, _label(first.group(1)) if first else ""))
            state = _drawn_state(rel, explicit, parents) if rel else None
            if state:
                label = label.replace("<div>", f"<div>{state}: ", 1)
                line = f'{indent}{src}-. "{label}" .->{dst}'
                styles.append(f"  linkStyle {index} stroke:{STATE_COLOURS[state]},"
                              f"stroke-width:2px")
            index += 1
        elif LINK.search(QUOTED.sub('""', line)):
            raise ExportError(f"a Mermaid line of a form the post-processing does not "
                              f"count as a link: `{line.strip()}`")
        lines.append(line)
    return "\n".join(lines + styles) + ("\n" if mermaid.endswith("\n") else "")


def exported(out: Path, workspace: str, view: str) -> str:
    """A view's Mermaid from an export, with its relationships styled."""
    diagram = (out / f"structurizr-{view}.mmd").read_text().strip()
    data = json.loads((out / f"{Path(workspace).stem}.json").read_text())
    return style_relationships(diagram, data).strip()


def render(source: Path, title: str) -> str:
    views = VIEW.findall((source / "views.dsl").read_text())
    if not views:
        sys.exit("design-map: no container or component views in views.dsl")
    parts = [header(title, sources_hash(source))]
    with tempfile.TemporaryDirectory() as tmp:
        export(source, Path(tmp))
        for kind, key, description in views:
            diagram = exported(Path(tmp), "map.dsl", key)
            parts.append(f"## {kind.capitalize()} view: {description}\n\n"
                         f"```mermaid\n{diagram}\n```\n")
    lifecycles = source / "lifecycles.md"
    if lifecycles.exists():
        parts.append(lifecycles.read_text().strip() + "\n")
    return "\n".join(parts)


class ChangeError(Exception):
    """The change file is not in the format; the message names the line."""


class Node:
    """One statement of the DSL: its line, its text and, for a block, its
    statements and the lines it spans."""

    def __init__(self, line: int, text: str, children: list["Node"], raw: list[str]):
        # A `{` stuck to the identifier (`!element a.b{`) reads as spaced.
        self.line, self.children, self.raw = line, children, raw
        self.text = re.sub(r"\s*\{$", " {", text.strip())

    def tags(self) -> list[tuple[int, list[str]]]:
        found = []
        for c in self.children:
            if c.text.split(None, 1)[:1] == ["tags"]:
                tags = QUOTED.findall(c.text)
                if any("," in t for t in tags):
                    raise ChangeError(f"line {c.line}: a tag holds a comma, which "
                                      f"Structurizr reads as two tags: `{c.text}`")
                found.append((c.line, tags))
        return found


def _shape(text: str, line: int) -> tuple[str, int]:
    """A line's text outside strings and `//` comments, and its opening less
    closing braces. The format takes one statement a line, a block's `{` at
    the end of its line and its `}` alone on one, and `//` comments."""
    bare = QUOTED.sub('""', text).strip()
    if bare.startswith("#") or "/*" in bare:
        raise ChangeError(f"line {line}: `{text.strip()}` is a comment of a form the "
                          f"format does not take; use `//` comments")
    bare = bare.split("//")[0].rstrip()
    opens, closes = bare.count("{"), bare.count("}")
    if opens and closes:
        raise ChangeError(f"line {line}: `{text.strip()}` opens and closes a block on "
                          f"one line; a block spans lines")
    if closes and bare != "}":
        raise ChangeError(f"line {line}: a block's `}}` goes on a line of its own: "
                          f"`{text.strip()}`")
    if opens and (opens > 1 or not bare.endswith("{")):
        raise ChangeError(f"line {line}: a block's `{{` goes at the end of its line, "
                          f"one to a line: `{text.strip()}`")
    return bare, opens - closes


def parse(lines: list[str], first: int = 1) -> list[Node]:
    """The statements of `lines`, a block's body, line numbers counted from
    `first`. A statement that opens a brace runs to the line that closes it."""
    nodes, i = [], 0
    while i < len(lines):
        bare, depth = _shape(lines[i], first + i)
        if not bare:
            i += 1
            continue
        j = i + 1
        while depth > 0:
            if j >= len(lines):
                raise ChangeError(f"line {first + i}: the block opened here is never closed")
            depth += _shape(lines[j], first + j)[1]
            j += 1
        body = lines[i + 1:j - 1] if j > i + 1 else []
        nodes.append(Node(first + i, lines[i], parse(body, first + i + 1), lines[i:j]))
        i = j
    return nodes


def _model(block: str, first: int) -> list[Node]:
    root = parse(block.splitlines(), first)
    if len(root) > 1:
        raise ChangeError(f"line {root[1].line}: `{root[1].text}` follows the "
                          f"extension's closing `}}`; a spare `}}` closes a block early")
    if not root:
        raise ChangeError(f"line {first}: expected one `workspace extends ... {{ }}`")
    for node in root[0].children:
        if re.match(r"model\s*\{", node.text):
            return node.children
    raise ChangeError(f"line {first}: the extension has no `model {{ }}`")


def _package(node: Node) -> int | None:
    """The one work package an entry names, None if it has no tags at all."""
    tags = node.tags()
    if not tags:
        return None
    named = [PACKAGE_TAG.match(t).group(1) for _, ts in tags for t in ts
             if PACKAGE_TAG.match(t)]
    if len(named) != 1:
        raise ChangeError(
            f"line {tags[0][0]}: `{node.text}` needs exactly one `wp:N` tag, "
            f"and has {len(named)}")
    return int(named[0])


def _declares(node: Node) -> bool:
    """Does this statement declare an element or a relationship?"""
    bare = QUOTED.sub('""', node.text)
    return "->" in bare or node.text.startswith(("!element", "!relationships")) \
        or bool(re.match(r"\w+\s*=", bare))


# The strings an element or relationship takes before its tags, by statement.
POSITIONAL = {"person": 2, "softwareSystem": 2, "container": 3, "component": 3,
              "relationship": 2}


def _check_inline_tags(node: Node) -> None:
    """Tags given as the last positional argument are outside the format."""
    bare = QUOTED.sub('""', node.text)
    if "->" in bare:
        kind = "relationship"
    elif match := re.match(r"(?:\w+\s*=\s*)?(person|softwareSystem|container|component)\b",
                           bare):
        kind = match.group(1)
    else:
        return
    if len(QUOTED.findall(node.text)) > POSITIONAL[kind]:
        raise ChangeError(f"line {node.line}: tags go on their own `tags` line, not "
                          f"as an argument: `{node.text}`")


class Item:
    """An entry (one `wp:` tag, kept whole) or a wrapper (an untagged
    `!element` holding items), with the identifier of the wrapper it sits in."""

    def __init__(self, node: Node, scope: str | None, package: int | None = None,
                 items: list["Item"] | None = None):
        self.node, self.scope, self.package, self.items = node, scope, package, items
        self.names: list[str] = []


def classify(nodes: list[Node], scope: str | None = None) -> list[Item]:
    """The model's statements as entries and wrappers, or an error naming the
    line of the first that is neither. One walk serves the validation and the
    filter."""
    items = []
    for node in nodes:
        package = _package(node)
        if package is not None:
            for child in node.children:
                if _declares(child):
                    raise ChangeError(
                        f"line {child.line}: `{node.text}` is tagged and holds "
                        f"element or relationship statements; put the children in "
                        f"their own untagged `!element` wrapper")
            _check_inline_tags(node)
            item = Item(node, scope, package)
            item.names = _names(item)
            items.append(item)
        elif node.text.startswith("!element ") and node.children:
            items.append(Item(node, scope, None,
                              classify(node.children, node.text.split()[1])))
        elif scope is not None:
            raise ChangeError(f"line {node.line}: a wrapper holds only entries, and "
                              f"`{node.text}` is not one")
        else:
            raise ChangeError(f"line {node.line}: `{node.text}` has no `wp:N` tag")
    return items


def _packages(items: list[Item]) -> set[int]:
    return {i.package for i in items if i.package is not None} | \
        {p for i in items if i.items for p in _packages(i.items)}


def entry_packages(block: str, first: int = 1) -> list[int]:
    """The work packages the extension's entries name, in number order."""
    return sorted(_packages(classify(_model(block, first))))


def _names(item: Item) -> list[str]:
    """The elements an entry draws: the one it changes, the one it declares,
    both ends of a relationship. A relationship is recognised by its `->`
    before anything else, so `r5 = a -> b` is one."""
    node, bare = item.node, QUOTED.sub('""', item.node.text)

    def ends(found: list[str]) -> list[str]:
        """Inside a wrapper an end must be fully qualified: a name without a
        dot would be read against the wrapper's scope by Structurizr."""
        for end in found:
            if item.scope is not None and "." not in end:
                raise ChangeError(f"line {node.line}: `{end}` in `{node.text}` is not "
                                  f"fully qualified (system.container.component)")
        return found

    if match := re.match(r'!relationships\s+"([^"]*)"', node.text):
        parts = [e.strip() for e in match.group(1).split("->")]
        return ends([e for e in parts if e and "*" not in e])
    if match := re.match(r"!element\s+(\S+)", node.text):
        return [match.group(1)]
    if match := re.match(r"(?:\w+\s*=\s*)?([\w.]+)\s*->\s*([\w.]+)", bare):
        return ends([match.group(1), match.group(2)])
    if match := re.match(r"(\w+)\s*=\s*\w+", bare):
        return [f"{item.scope}.{match.group(1)}" if item.scope else match.group(1)]
    raise ChangeError(f"line {node.line}: `{node.text}` is not an element or a relationship")


def package_entries(block: str, package: int, first: int = 1) -> tuple[str, list[str]]:
    """The model statements holding only `package`'s entries, and the names of
    the elements they draw. A wrapper is kept, holding only those entries, if
    any of its children is kept."""
    names: list[str] = []

    def keep(items: list[Item]) -> list[str]:
        out: list[str] = []
        for item in items:
            if item.package is not None:
                if item.package == package:
                    out += item.node.raw
                    names.extend(item.names)
            else:
                inner = keep(item.items)
                if inner:
                    out += [item.node.raw[0], *inner, item.node.raw[-1]]
        return out

    lines = keep(classify(_model(block, first)))
    return "\n".join(lines) + "\n", list(dict.fromkeys(names))


def view_kind(names: list[str]) -> tuple[str, str]:
    """A Component view of the container all the package's components belong
    to, else a Container view of their system. A name of three or more parts
    is a component (system.container.component, with hierarchical ids)."""
    components = [n for n in names if n.count(".") >= 2]
    containers = sorted({".".join(n.split(".")[:2]) for n in components})
    if len(containers) == 1:
        return "component", containers[0]
    systems = sorted({n.split(".")[0] for n in names if "." in n})
    if len(systems) != 1:
        raise ChangeError(f"the package's elements {names} do not share one software "
                          f"system, so no container view can show them")
    return "container", systems[0]


def package_view(package: int, title: str, names: list[str]) -> str:
    """The DSL of a package's own view."""
    kind, scope = view_kind(names)
    if kind == "container":
        shown = [".".join(n.split(".")[:2]) for n in names]
    else:
        shown = names
    included = "\n".join(f"            include {n}" for n in dict.fromkeys(shown))
    title = title.replace('"', "'")
    return (f'        {kind} {scope} "wp-{package}" "{title}" {{\n{included}\n'
            f"        }}\n")


def package_titles(text: str) -> dict[int, str]:
    """A heading outside a code block that names `#N` titles package N."""
    titles, fenced = {}, False
    for line in text.splitlines():
        if line.startswith("```"):
            fenced = not fenced
        elif not fenced and (heading := HEADING.match(line)):
            for number in re.findall(r"#(\d+)\b", heading.group(1)):
                titles.setdefault(int(number), heading.group(1))
    return titles


def structurizr_block(text: str) -> tuple[str, int]:
    """The first `structurizr` fenced block, and the line it starts on."""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        if line.strip() == "```structurizr":
            for j in range(i + 1, len(lines)):
                if lines[j].startswith("```"):
                    return "\n".join(lines[i + 1:j]), i + 2
            break
    raise ChangeError("no closed ```structurizr block in the change file")


def change_hash(change: Path, source: Path) -> str:
    """One hash over the change file and the map it extends."""
    h = hashlib.sha256()
    h.update(change.read_bytes() + b"\0" + sources_hash(source).encode())
    return h.hexdigest()


def change_header(title: str, change_name: str, digest: str) -> str:
    return f"""# {title}

**Generated by the programme's `scripts/docs/design-map/design-map.py --change`
from [{change_name}]({change_name}) and the application's `docs/design-map/`.
Do not edit.**

Green is new, yellow changed, red removed. A relationship's label starts with
its state too. Each work package is drawn alone: the packages it builds on are
not applied.

Sources hash: `{digest}`.
"""


def change_target(change: Path) -> Path:
    return change.with_name(change.name.replace("-map-change.md", "-map-diagrams.md"))


def change_is_current(change: Path, source: Path, target: Path) -> bool:
    found = HASH.search(target.read_text()) if target.exists() else None
    return bool(found) and found.group(1) == change_hash(change, source)


def render_change(change: Path, source: Path) -> str:
    text = change.read_text()
    block, first = structurizr_block(text)
    packages = entry_packages(block, first)
    if not packages:
        raise ChangeError("the extension has no entries")
    titles = package_titles(text)
    h1 = next((m.group(1) for line in text.splitlines()
               if (m := re.match(r"# (.*\S)", line))), change.stem)
    parts = [change_header(f"{h1}, drawn", change.name, change_hash(change, source))]
    for package in packages:
        entries, names = package_entries(block, package, first)
        title = titles.get(package, f"WP for wp:{package}")
        with tempfile.TemporaryDirectory() as tmp:
            work = Path(tmp) / "map"
            shutil.copytree(source, work)
            (work / "change.dsl").write_text(
                "workspace extends model.dsl {\n    model {\n" + entries + "    }\n"
                "    views {\n" + package_view(package, title, names)
                + "        !include views.dsl\n    }\n}\n")
            out = Path(tmp) / "out"
            out.mkdir()
            export(work, out, "change.dsl")
            diagram = exported(out, "change.dsl", f"wp-{package}")
        parts.append(f"## {title}\n\n```mermaid\n{diagram}\n```\n")
    return "\n".join(parts)


def change_main(args: list[str]) -> int:
    change, mode = Path(args[1]), args[2]
    root, source, _ = paths()
    target = change_target(change)
    if not change.is_file() or target == change or not source.is_dir():
        print(f"design-map: {change} is not a change file (N-map-change.md) of an "
              f"application with docs/design-map/", file=sys.stderr)
        return 2
    try:
        if mode == "--write":
            target.write_text(render_change(change, source))
            print(f"design-map: wrote {target}")
            return 0
    except (ChangeError, ExportError) as e:
        print(f"design-map: {change.name}: {e}", file=sys.stderr)
        return 1
    except subprocess.CalledProcessError as e:
        print(f"design-map: the Structurizr export failed (docker exit {e.returncode})",
              file=sys.stderr)
        return 1
    if not change_is_current(change, source, target):
        print(f"design-map: {target.name} is STALE: its sources changed since it was "
              f"drawn", file=sys.stderr)
        return 1
    print(f"design-map: {target.name} is current")
    return 0


def main() -> int:
    args = sys.argv[1:]
    if len(args) == 3 and args[0] == "--change" and args[2] in ("--write", "--check"):
        return change_main(args)
    if args not in (["--write"], ["--check"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    root, source, target = paths()
    if not source.is_dir():
        print("design-map: not applicable here: the application has no docs/design-map/")
        return 0
    name = target.relative_to(root)
    if args == ["--write"]:
        number = target.name.split("-", 1)[0]
        try:
            target.write_text(render(source, f"{number} Design map"))
        except ExportError as e:
            print(f"design-map: {e}", file=sys.stderr)
            return 1
        except subprocess.CalledProcessError as e:
            print(f"design-map: the Structurizr export failed (docker exit {e.returncode})",
                  file=sys.stderr)
            return 1
        print(f"design-map: wrote {name}")
        return 0
    found = HASH.search(target.read_text()) if target.exists() else None
    if not found or found.group(1) != sources_hash(source):
        print(f"design-map: {name} is STALE: its sources changed since it was drawn",
              file=sys.stderr)
        return 1
    print(f"design-map: {name} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
