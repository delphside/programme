#!/usr/bin/env python3
"""design-map.py — draws an application's design map, `docs/R.2.0-design-map.md`.

The source is the application's `docs/design-map/`: `model.dsl` (the C4
model), `views.dsl` (its views) and `map.dsl` (the model with the views), in
Structurizr's DSL. The views are exported to Mermaid, never drawn by hand.
R is the application's document range, from its programme profile.

**Two commands, and only one needs Docker.**

  design-map.py --write   export map.dsl through the Structurizr image, pinned
                          by digest in IMAGE, and write the document
  design-map.py --check   exit 1 if the sources' hash differs from the one in
                          the document's header; plain Python, no Docker

The hash covers every file in `docs/design-map/`, so `--check` says
"regenerate" for any change to the sources, and `check-docs.sh` can run it in
hooks and cloud sessions where Docker is not available. A hand edit to the
generated document is not caught by the hash; the header says not to make one.

Each view becomes a section titled by its C4 type and its description in
views.dsl, in the order views.dsl lists them. `lifecycles.md`, when it exists,
is appended as it stands.
"""
import hashlib
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from board import profile  # noqa: E402

IMAGE = ("structurizr/structurizr@sha256:"
         "721136283c2f9cf1ba69037bc9de136c579d66fdcb2d771cb60546ec68def1a5")

VIEW = re.compile(r'^\s*(container|component)\s+\S+\s+"([^"]+)"\s+"([^"]+)"', re.M)
HASH = re.compile(r"^Sources hash: `([0-9a-f]{64})`\.$", re.M)


def paths() -> tuple[Path, Path, Path]:
    root = profile.app_root()
    rng = profile.application_profile(root)["identity"]["document_range"]
    return root, root / "docs" / "design-map", root / "docs" / f"{rng}.2.0-design-map.md"


def sources_hash(source: Path) -> str:
    """One hash over every file's name and bytes, in name order."""
    h = hashlib.sha256()
    for f in sorted(p for p in source.rglob("*") if p.is_file()):
        h.update(f.relative_to(source).as_posix().encode() + b"\0")
        h.update(f.read_bytes() + b"\0")
    return h.hexdigest()


def header(title: str, digest: str) -> str:
    return f"""# {title}

**Generated by the programme's `scripts/docs/design-map/design-map.py` from
[`design-map/`](design-map/). Do not edit.**

The application as it is on `main`, drawn from one model. To change a
diagram, change [`model.dsl`](design-map/model.dsl) and run the script with
`--write`. Each element's `artefact` property in `model.dsl` names the file or
crate that implements it.

Sources hash: `{digest}`.
"""


def export(source: Path, out: Path) -> None:
    subprocess.run(
        ["docker", "run", "--rm", "-u", f"{os.getuid()}:{os.getgid()}",
         "-v", f"{source}:/w:ro", "-v", f"{out}:/out", "-w", "/w", IMAGE,
         "export", "-w", "map.dsl", "-f", "mermaid", "-o", "/out"],
        check=True, stdout=subprocess.DEVNULL)


def render(source: Path, title: str) -> str:
    views = VIEW.findall((source / "views.dsl").read_text())
    if not views:
        sys.exit("design-map: no container or component views in views.dsl")
    parts = [header(title, sources_hash(source))]
    with tempfile.TemporaryDirectory() as tmp:
        export(source, Path(tmp))
        for kind, key, description in views:
            diagram = (Path(tmp) / f"structurizr-{key}.mmd").read_text().strip()
            parts.append(f"## {kind.capitalize()} view: {description}\n\n"
                         f"```mermaid\n{diagram}\n```\n")
    lifecycles = source / "lifecycles.md"
    if lifecycles.exists():
        parts.append(lifecycles.read_text().strip() + "\n")
    return "\n".join(parts)


def main() -> int:
    args = sys.argv[1:]
    if args not in (["--write"], ["--check"]):
        print(__doc__.strip(), file=sys.stderr)
        return 2
    root, source, target = paths()
    if not source.is_dir():
        print("design-map: not applicable here: the application has no docs/design-map/")
        return 0
    name = target.relative_to(root)
    if args == ["--write"]:
        number = target.name.split("-", 1)[0]
        target.write_text(render(source, f"{number} Design map"))
        print(f"design-map: wrote {name}")
        return 0
    found = HASH.search(target.read_text()) if target.exists() else None
    if not found or found.group(1) != sources_hash(source):
        print(f"design-map: {name} is STALE: its sources changed since it was drawn",
              file=sys.stderr)
        return 1
    print(f"design-map: {name} is current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
